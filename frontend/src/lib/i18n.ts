const dictionaries: Record<Lang, Record<Key, string>> = { fa, en };
const locales: Record<Lang, string> = { fa: "fa-IR", en: "en-US" };

export type Params = Record<string, string | number>;

export type I18n = {
  lang: Lang;
  locale: string;
  /**
   * The text for `key`, with {name} placeholders filled; numbers use the language's digits.
   * {count:card:cards} picks the singular or plural word after the number (used in English).
   */
  t: (key: Key, params?: Params) => string;
  /** A number with the language's digits. */
  num: (n: number) => string;
};

export function makeI18n(lang: Lang): I18n {
  const locale = locales[lang];
  const num = (n: number) => n.toLocaleString(locale);
  const t = (key: Key, params?: Params) =>
    dictionaries[lang][key].replace(/\{(\w+)(?::([^:}]*):([^}]*))?\}/g, (whole, name, one, other) => {
      const value = params?.[name];
      if (value === undefined) return whole;
      const text = typeof value === "number" ? num(value) : value;
      return one === undefined ? text : `${text} ${value === 1 ? one : other}`;
    });
  return { lang, locale, t, num };
}

/** Set by the page for the chosen language; components outside it (tests) get Persian. */
export const I18nContext = createContext<I18n>(makeI18n("fa"));
export const useI18n = () => useContext(I18nContext);

/** Puts the language on <html> (direction, lang, title) and remembers it in this browser. */
export function applyLang(lang: Lang) {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === "fa" ? "rtl" : "ltr";
  document.title = dictionaries[lang]["brand.name"];
  try {
    localStorage.setItem(LANG_KEY, lang);
  } catch {}
}

/** The language this browser last used (set by langScript on <html>), before any profile is loaded. */
export const browserLang = (): Lang =>
  typeof document !== "undefined" && document.documentElement.lang === "en" ? "en" : "fa";
